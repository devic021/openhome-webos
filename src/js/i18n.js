const I18N_TABLES={sr:I18N_SR};

// Which BCP-47 locale to format dates and times with. Weekday and month names come from the
// platform, not from the table above, so a language needs this too - otherwise picking English
// still leaves the date reading "Sreda, 21.10.2026".
const I18N_LOCALES={en:"en-GB",sr:"sr-Latn"};

let i18nlang=null;      // resolved code: "en" | "sr" | ...

// What the TV's interface is set to. navigator.language reflects the webOS UI locale on this
// platform, which is what a viewer actually reads the rest of the system in.
function i18ndetect(){
	const tag=String((navigator && navigator.language) || "en").toLowerCase();
	const base=tag.split("-")[0];
	return I18N_TABLES[base]?base:"en";
}

// The chosen language is read straight out of storage, not from `prefs`.
//
// Two reasons, and the first one is fatal: settings.js calls t() while building its schema, which
// happens BEFORE its own `let prefs` is initialised - and `typeof prefs` does not protect you
// there, a let binding in the temporal dead zone throws on any mention. The second is that even
// if it did not throw, prefs are loaded after the schema is built, so an explicit choice would
// never reach the settings labels at all.
const I18N_PREFS_KEY="openlauncher.prefs";

function i18nwanted(){
	try {
		const saved=JSON.parse(localStorage.getItem(I18N_PREFS_KEY) || "{}");
		return saved.language || "auto";
	} catch(e) { return "auto"; }
}

function i18nresolve(){
	const want=i18nwanted();
	i18nlang=(want==="auto")?i18ndetect():want;
	if(want!=="auto" && want!=="en" && !I18N_TABLES[want]){ i18nlang="en"; }
	return i18nlang;
}

function i18nlocale(){
	if(i18nlang===null){ i18nresolve(); }
	return I18N_LOCALES[i18nlang] || "en-GB";
}

// t("Settings") -> "Podešavanja" on a Serbian TV, "Settings" everywhere else.
// t("{n} apps", {n:5}) fills placeholders after translating.
// A number with one decimal place, in the launcher's own language: 7.2 in English, 7,2 in
// Serbian. Two places in the system panel used to force a comma, which read as Serbian even
// when everything around it was English.
function i18nnum(value,places){
	if(!isFinite(value)){ return "-"; }
	const digits=(places===undefined)?1:places;
	try {
		return value.toLocaleString(i18nlocale(),{minimumFractionDigits:0,maximumFractionDigits:digits});
	} catch(e) {
		return String(Math.round(value*Math.pow(10,digits))/Math.pow(10,digits));
	}
}

function t(text,values){
	if(i18nlang===null){ i18nresolve(); }
	const table=I18N_TABLES[i18nlang];
	let out=(table && table[text]) || text;
	if(values){
		Object.keys(values).forEach((name) => {
			out=out.split("{"+name+"}").join(String(values[name]));
		});
	}
	return out;
}


// Attributes written straight into index.html cannot call t() - the page is not JavaScript. They
// carry data-i18n-title instead and are translated once the document is there.
// index.html is written in English and the three markers below say what to translate in it:
//   data-i18n              the element's own text
//   data-i18n-title        its title (and aria-label, which always matches)
//   data-i18n-placeholder  the placeholder of a text box
document.addEventListener("DOMContentLoaded",function(){
	const titled=document.querySelectorAll("[data-i18n-title]");
	for(let i=0;i<titled.length;i++){
		const node=titled[i];
		const source=node.getAttribute("title");
		if(!source){ continue; }
		const translated=t(source);
		node.setAttribute("title",translated);
		if(node.hasAttribute("aria-label")){ node.setAttribute("aria-label",translated); }
	}
	const texts=document.querySelectorAll("[data-i18n]");
	for(let i=0;i<texts.length;i++){
		const node=texts[i];
		const source=node.textContent.trim();
		if(source){ node.textContent=t(source); }
	}
	// Generated content (#folderbar::before) is drawn by CSS, where t() cannot reach. The word is
	// handed over as a custom property instead - quoted, because that is what content: expects.
	document.documentElement.style.setProperty("--apps-title",JSON.stringify(t("Apps")));
	const holders=document.querySelectorAll("[data-i18n-placeholder]");
	for(let i=0;i<holders.length;i++){
		const node=holders[i];
		const source=node.getAttribute("placeholder");
		if(source){ node.setAttribute("placeholder",t(source)); }
	}
});

// This file loads BEFORE settings.js, because settings.js calls t() while it is building its
// schema. So the schema cannot be extended here at load time - it does not exist yet. Both the
// language row and the setpref wrapper wait for the document instead.
document.addEventListener("DOMContentLoaded",function(){
	if(typeof SETTINGS_SCHEMA==="undefined"){ return; }
	// first tab, first item: it decides how everything else reads
	const first=SETTINGS_SCHEMA[0];
	if(!first){ return; }
	first.items.unshift({
		key:"language",label:"Language",type:"choice",stepper:true,default:"auto",
		options:I18N_LANGUAGES,
		hint:"Automatic follows the TV's own interface language. Changing this reloads the launcher."
	});

	// Every string in this launcher is a literal baked into the page when it was built, so the
	// honest way to change language is to build the page again. setpref is the single funnel for
	// preference changes, so it is wrapped here rather than patching settings.js.
	const setprefwas=window.setpref;
	window.setpref=function(key,value){
		const was=(typeof prefs!=="undefined" && prefs)?prefs.language:undefined;
		const result=setprefwas.apply(this,arguments);
		if(key==="language" && value!==was){
			i18nresolve();
			setTimeout(() => { location.reload(); },200);
		}
		return result;
	};
});
